/** Book ids in canonical order, Genesis to Revelation. */
export const CANON: string[] = Object.keys(BOOK_ORDER);

/** Display name for a book id, falling back to the id itself. */
export function bookName(id: string): string {
  return BOOK_NAMES[id] ?? id;
}

/** Sort comparator putting book ids in canonical order. */
export function byCanonicalOrder(a: string, b: string): number {
  return (BOOK_ORDER[a] ?? 999) - (BOOK_ORDER[b] ?? 999);
}
