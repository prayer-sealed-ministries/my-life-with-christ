#!/usr/bin/env node
/**
 * Write screenshots/INDEX.md: what is in the folder, and what it is evidence of.
 *
 * Sixty-two PNGs in a nested folder tree say nothing about which build produced
 * them. They were previously written to `screenshots/<theme>/<width>/` with no
 * record of the data profile at all, so a reviewer could not tell whether they
 * were looking at the purchased outlines, the BSB sections, or bare chapters —
 * and the images outlive the build that made them.
 *
 * The capture writes a CAPTURED.json per profile, reading the profile off the
 * running build rather than off DATA_PROFILE. This walks those and reports.
 * It fails rather than writing a cheerful empty index: an index of nothing is
 * the same failure as a check that examines nothing.
 *
 * Usage: node scripts/screenshot-index.mjs
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const ROOT = 'screenshots';

/** A folder is only a capture if it says what it captured. */
const MINIMUM_IMAGES_PER_PROFILE = 20;

if (!existsSync(ROOT)) {
  console.error(`${ROOT}/ does not exist. Run: npm run screenshots`);
  process.exit(1);
}

function walk(dir) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...walk(path));
    else if (entry.name.endsWith('.png')) found.push({ path, bytes: statSync(path).size });
  }
  return found;
}

const profiles = readdirSync(ROOT, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const captures = [];
const unstamped = [];

for (const name of profiles) {
  const stampPath = join(ROOT, name, 'CAPTURED.json');
  const images = walk(join(ROOT, name));
  if (!existsSync(stampPath)) {
    unstamped.push({ name, count: images.length });
    continue;
  }
  captures.push({ ...JSON.parse(readFileSync(stampPath, 'utf8')), dir: name, images });
}

if (unstamped.length > 0) {
  console.error('These folders hold screenshots with no record of the build that made them:');
  for (const { name, count } of unstamped) {
    console.error(`  ${ROOT}/${name} — ${count} image(s), no CAPTURED.json`);
  }
  console.error('\nThey are from an older capture layout. Delete them and re-run the capture.');
  process.exit(1);
}

if (captures.length === 0) {
  console.error('No captures found. Run: npm run screenshots');
  process.exit(1);
}

for (const capture of captures) {
  if (capture.images.length < MINIMUM_IMAGES_PER_PROFILE) {
    console.error(
      `${ROOT}/${capture.dir} holds only ${capture.images.length} images, below the floor of ` +
        `${MINIMUM_IMAGES_PER_PROFILE}. The capture did not finish.`,
    );
    process.exit(1);
  }
}

let commit = 'unknown';
try {
  commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
  /* not a git checkout; the stamp is still useful without it */
}

const lines = [
  '# Screenshots',
  '',
  'Evidence, not assertions. Generated by `npm run screenshots`.',
  '',
  'Each folder is one data profile, read from the running build via the',
  '`data-data-profile` attribute the build stamps on `<html>` — not from the',
  '`DATA_PROFILE` environment variable, which says what was *asked for* rather',
  'than what the served bundle actually carried.',
  '',
  `Repository commit at index time: \`${commit}\``,
  '',
];

for (const capture of captures) {
  const bytes = capture.images.reduce((total, image) => total + image.bytes, 0);
  lines.push(
    `## \`${capture.profile}\``,
    '',
    `- ${capture.images.length} images, ${Math.round(bytes / 1024)}kB`,
    `- captured ${capture.capturedAt}`,
    `- served from ${capture.servedFrom ?? 'unrecorded'}`,
    '',
  );
  for (const image of capture.images.map((image) => image.path).sort()) {
    lines.push(`- \`${image}\``);
  }
  lines.push('');
}

writeFileSync(join(ROOT, 'INDEX.md'), `${lines.join('\n')}\n`);

console.log(`${ROOT}/INDEX.md written`);
for (const capture of captures) {
  console.log(`  ${capture.profile.padEnd(10)} ${capture.images.length} images`);
}
