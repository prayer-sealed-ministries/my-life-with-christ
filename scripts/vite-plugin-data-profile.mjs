/**
 * Build-time gate on the purchased outline content.
 *
 * The Blueprint outlines are purchased third-party material (see DATA-LICENSE.md).
 * Their reference data — book, chapter, verse — is bare fact and carries no
 * copyright. Their *titles* and their *intro prose* are the author's expression
 * and are the part that must not be published.
 *
 * DATA_PROFILE picks which of those ships:
 *
 *   full       outlines + intros + KJV   (private use; the default)
 *   refs-only  chapter/verse + KJV       (publishable; titles and intros absent)
 *
 * This is a single switch rather than conditionals scattered through the app,
 * and it works by *generating the module source*: under `refs-only` the
 * protected strings are never written into the module graph at all, so they
 * cannot survive into the bundle by way of a missed branch or a dead-code
 * elimination that did not fire. `npm run verify:bundle` greps the built output
 * to prove it, rather than trusting this file.
 */

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const VIRTUAL_ID = 'virtual:journey-data';
const RESOLVED_ID = `\0${VIRTUAL_ID}`;

export const DATA_PROFILES = ['full', 'refs-only'];

/** Fields dropped from every outline entry under `refs-only`. */
const PROTECTED_ENTRY_FIELDS = ['title', 'displayTitle', 'series', 'sourceRef'];

export function resolveProfile(value) {
  const profile = value ?? process.env.DATA_PROFILE ?? 'full';
  if (!DATA_PROFILES.includes(profile)) {
    throw new Error(`DATA_PROFILE must be one of ${DATA_PROFILES.join(', ')} — got "${profile}"`);
  }
  return profile;
}

/**
 * Strip a full outlines dataset down to bare references.
 *
 * Exported for the bundle verifier and its tests, so the definition of "what is
 * protected" lives in exactly one place.
 */
export function stripToRefs(books) {
  return books.map((book) => ({
    id: book.id,
    name: book.name,
    testament: book.testament,
    order: book.order,
    // The author's prose. Dropped entirely, not truncated.
    intro: '',
    entries: book.entries.map((entry) => {
      const stripped = { ...entry };
      for (const field of PROTECTED_ENTRY_FIELDS) delete stripped[field];
      delete stripped.adjudicated;
      delete stripped.unresolved;
      return stripped;
    }),
  }));
}

/** @param {{profile?: string, root?: string}} options */
export default function dataProfilePlugin(options = {}) {
  const profile = resolveProfile(options.profile);
  const root = options.root ?? process.cwd();

  return {
    name: 'journey:data-profile',

    config() {
      return { define: { __DATA_PROFILE__: JSON.stringify(profile) } };
    },

    resolveId(id) {
      return id === VIRTUAL_ID ? RESOLVED_ID : null;
    },

    load(id) {
      if (id !== RESOLVED_ID) return null;

      const outlines = JSON.parse(readFileSync(resolve(root, 'src/data/outlines.json'), 'utf8'));
      const shipped = profile === 'full' ? outlines : stripToRefs(outlines);

      return [
        `// Generated by vite-plugin-data-profile. Do not edit.`,
        `export const DATA_PROFILE = ${JSON.stringify(profile)};`,
        `export const hasOutlineTitles = ${profile === 'full'};`,
        `export const outlines = ${JSON.stringify(shipped)};`,
        `export default outlines;`,
      ].join('\n');
    },

    buildStart() {
      this.info?.(`DATA_PROFILE=${profile}`);
    },
  };
}
